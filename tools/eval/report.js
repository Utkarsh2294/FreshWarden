import { readFile, writeFile } from 'node:fs/promises';
async function read(name) {
  try {
    return JSON.parse(
      await readFile(`docs/evaluation/${name}-results.json`, 'utf8'),
    );
  } catch {
    return null;
  }
}
const [dispatch, load, inward, shelf, indexes] = await Promise.all(
  ['dispatch', 'load', 'inward', 'shelf', 'index'].map(read),
);
const n = inward?.length || 0,
  f = (value) =>
    value == null
      ? 'NOT RUN'
      : typeof value === 'number'
        ? value.toFixed(2)
        : value;
const rows = [
  ['Dispatch synthetic orders', dispatch?.orders, dispatch?.measuredAt],
  [
    'Unsafe orders blocked',
    dispatch ? `${dispatch.blockedBad}/${dispatch.badOrders}` : null,
    'Seeded rejected stock',
  ],
  [
    'False blocks in controlled sample',
    dispatch?.falseBlocks,
    'Normal synthetic telemetry',
  ],
  [
    'Sequential dispatch p50 / p95 (ms)',
    dispatch ? `${f(dispatch.p50Ms)} / ${f(dispatch.p95Ms)}` : null,
    'Local HTTP + real temporary Mongo replica set',
  ],
  [
    '50 rps attempts / response statuses',
    load ? `${load.attempts} / ${JSON.stringify(load.statuses)}` : null,
    '3-second burst; production rate limiting retained',
  ],
  [
    'Burst p95, including throttled responses (ms)',
    load?.p95Ms,
    load?.measuredAt,
  ],
  [
    'Real inward photo dataset',
    n || null,
    'Required: 200 labelled photos; no synthetic accuracy claim',
  ],
  [
    'Date accuracy / amber / false accepts / Gemini share',
    n
      ? `${inward.filter((r) => r.dateMatch).length}/${n} matched; ${inward.filter((r) => r.status === 'amber').length} amber; ${inward.filter((r) => r.falseAccept).length} false accepts; OCR/Gemini routing share not measured by vision-only evaluator`
      : null,
    'Live provider + real photos required',
  ],
  [
    'Shelf real-photo dataset',
    shelf?.datasetSize,
    shelf?.measuredAt || 'Required: 40 staged photos and human labels',
  ],
  [
    'Physical fridge detection delay / false alarms',
    null,
    'Sensor, calibrated reference and door-open test required',
  ],
  [
    'Lot query documents / keys examined',
    indexes ? `${indexes.documentsExamined} / ${indexes.keysExamined}` : null,
    '12-lot dataset only; not a scaling benchmark',
  ],
];
let report = `# Measured evaluation\n\nGenerated by \`node tools/eval/report.js\` at ${new Date().toISOString()}. Source JSON is in docs/evaluation. NOT RUN means no evidence is available, never zero errors or perfect accuracy.\n\n| Measurement | Result | Scope / date |\n|---|---|---|\n${rows.map(([a, b, c]) => `| ${a} | ${f(b)} | ${c || 'NOT RUN'} |`).join('\n')}\n\nThe 120-request/minute/IP ceiling can throttle a 50-rps burst; 429 is reported separately from application errors. This prototype has not established sustained network-scale capacity. No photo/model/hardware/usability acceptance is implied by unit tests. Run \`NODE_ENV=test node tools/eval/runLocalBench.js\` to reproduce isolated local measurements.\n`;
if (shelf) {
  report += '\n| Shelf finding | Precision | Recall |\n|---|---|---|\n';
  for (const [type, { tp, fp, fn }] of Object.entries(shelf.counts))
    report += `| ${type} | ${tp + fp ? f(tp / (tp + fp)) : 'Unavailable'} | ${tp + fn ? f(tp / (tp + fn)) : 'Unavailable'} |\n`;
}
await writeFile('docs/eval.md', report);
console.log(
  'Generated docs/eval.md from measured artifacts and explicit missing-data states.',
);
